export function samplePharmacyCamera(t, state, eye, target) {
  sampleCameraKeys(shots, t, eye, target);
  if (t >= .685 && t < .859) {
    const progress = MathUtils.smoothstep(t, .685, .859);
    const tracking = MathUtils.smoothstep(t, .685, .705) * (1 - MathUtils.smoothstep(t, .838, .859));
    eye.x = MathUtils.lerp(eye.x, state.carX + MathUtils.lerp(5.3, 6.5, progress), tracking);
    target.x = MathUtils.lerp(target.x, state.carX - .6 * (1 - progress), tracking);
  }
}
